import fs from 'node:fs';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost/', pretendToBeVisual: true });
global.window = dom.window; global.document = dom.window.document; global.HTMLElement = dom.window.HTMLElement; global.self = dom.window;
const THREE = await import('three');
const { GLTFLoader } = await import('three/addons/loaders/GLTFLoader.js');
const { mergeSkinnedParts } = await import('../src/entities/characterMerge.js');
const { clone } = await import('three/addons/utils/SkeletonUtils.js');
const CHARS = 'public/assets/models/chars';
const file = process.argv[2] ?? 'q_adventurer.glb';
const buf = fs.readFileSync(`${CHARS}/${file}`);
const gltf = await new Promise((res, rej) => new GLTFLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '', res, rej));
const s = clone(gltf.scene);
s.updateMatrixWorld(true);
const b1 = new THREE.Box3().setFromObject(s);
console.log('przed scaleniem:', (b1.max.y - b1.min.y).toFixed(3), b1.min.y.toFixed(3));
const res = mergeSkinnedParts(s);
s.updateMatrixWorld(true);
const b2 = new THREE.Box3().setFromObject(s);
console.log('po scaleniu:', (b2.max.y - b2.min.y).toFixed(3), b2.min.y.toFixed(3), JSON.stringify(res));
let geoBox = null;
s.traverse((o) => { if (o.isMesh) { o.geometry.computeBoundingBox(); geoBox = o.geometry.boundingBox; } });
if (geoBox) console.log('geo bbox:', geoBox.min.toArray().map(v=>v.toFixed(2)).join(','), '→', geoBox.max.toArray().map(v=>v.toFixed(2)).join(','));
